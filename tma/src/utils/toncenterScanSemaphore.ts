// src/utils/toncenterScanSemaphore.ts
// Общий бюджет параллельных toncenter-запросов на ВСЕ фоновые сканы разом:
// ActiveAuctions.tsx (аукционы), ProfileWidget.tsx (свои аукционы + подсчёт
// прибыли). Раньше у каждого был свой независимый пул concurrency=10 —
// тюнилось как "максимум для одного сканера без 429 при ~25 rps плане", но
// если 2-3 скана шли одновременно (обычная ситуация — ProfileWidget и
// ActiveAuctions смонтированы разом), суммарный burst выходил далеко за
// пределы 25 rps и ловил 429 (см. Log.md 2026-09-04, баг "Сделать ставку").
// Один и тот же семафор на всех сканерах держит их суммарно в рамках
// исходного лимита независимо от того, сколько из них работает прямо
// сейчас — если сканер один, ему достаётся весь бюджет; если несколько,
// делят его между собой по мере освобождения слотов.
import { createSemaphore } from "./concurrency";

const TONCENTER_SCAN_BUDGET = 10;

export const toncenterScanSemaphore = createSemaphore(TONCENTER_SCAN_BUDGET);
